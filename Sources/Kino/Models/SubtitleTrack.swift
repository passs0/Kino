import Foundation

/// Position placement of a subtitle cue on the video canvas.
public enum SubtitlePosition: String, Sendable {
    case bottom
    case top
    case center
}

/// Placement strategy for subtitles when media does not fill the display aspect ratio.
public enum SubtitlePlacement: String, CaseIterable, Identifiable, Sendable {
    case letterbox = "letterbox"     // Sit according to display height (in letterbox bar)
    case mediaFrame = "mediaFrame"   // Sit according to media height (inside video frame)

    public var id: String { rawValue }

    public var title: String {
        switch self {
        case .letterbox:
            return "Display Height (In Letterbox Bar)"
        case .mediaFrame:
            return "Media Height (Inside Video)"
        }
    }
}

/// Individual subtitle cue containing start time, end time, plain text, and layout position.
public struct SubtitleCue: Identifiable, Sendable {
    public let id = UUID()
    public let startTime: Double
    public let endTime: Double
    public let text: String
    public let position: SubtitlePosition

    public init(startTime: Double, endTime: Double, text: String, position: SubtitlePosition = .bottom) {
        self.startTime = startTime
        self.endTime = endTime
        self.text = text
        self.position = position
    }
}

/// Represents an available subtitle track (embedded local stream or online WebVTT).
public struct SubtitleTrack: Identifiable, Hashable, Sendable {
    public let id: String
    public let name: String
    public let languageCode: String?
    public let isAutoGenerated: Bool
    public var vttURL: URL?
    public let streamIndex: Int?
    public let sourceURL: URL?
    public let isDefault: Bool

    public init(
        id: String,
        name: String,
        languageCode: String? = nil,
        isAutoGenerated: Bool = false,
        vttURL: URL? = nil,
        streamIndex: Int? = nil,
        sourceURL: URL? = nil,
        isDefault: Bool = false
    ) {
        self.id = id
        self.name = name
        self.languageCode = languageCode
        self.isAutoGenerated = isAutoGenerated
        self.vttURL = vttURL
        self.streamIndex = streamIndex
        self.sourceURL = sourceURL
        self.isDefault = isDefault
    }
}

/// Fast WebVTT, SRT, ASS/SSA, and LRC parser converting raw subtitle text into timestamped cues with semantic positioning.
public enum SubtitleParser {
    public static func parse(_ raw: String) -> [SubtitleCue] {
        var clean = raw
        if clean.hasPrefix("\u{FEFF}") {
            clean = String(clean.dropFirst())
        }
        clean = clean.trimmingCharacters(in: .whitespacesAndNewlines)

        if clean.contains("[Events]") || clean.contains("\nDialogue:") || clean.hasPrefix("Dialogue:") {
            return parseASS(clean)
        }
        if isLRCContent(clean) {
            return parseLRC(clean)
        }
        return parseWebVTT(clean)
    }

    private static func isLRCContent(_ text: String) -> Bool {
        // Quick check for LRC format [MM:SS.xx]
        guard !text.contains("-->") && !text.contains("Dialogue:") else { return false }
        return text.contains("[0") || text.contains("[1") || text.contains("[2") || text.contains("[3")
    }

    public static func parseLRC(_ raw: String) -> [SubtitleCue] {
        var rawCues: [(time: Double, text: String)] = []
        let lines = raw.components(separatedBy: .newlines)
        let regex = try? NSRegularExpression(pattern: #"\[(\d{1,2}):(\d{2})(?:[.:](\d{1,3}))?\]"#)

        for line in lines {
            let trimmed = line.trimmingCharacters(in: .whitespacesAndNewlines)
            if trimmed.isEmpty || trimmed.hasPrefix("[ti:") || trimmed.hasPrefix("[ar:") || trimmed.hasPrefix("[al:") || trimmed.hasPrefix("[by:") {
                continue
            }

            guard let regex = regex else { continue }
            let matches = regex.matches(in: trimmed, range: NSRange(location: 0, length: trimmed.utf16.count))
            guard !matches.isEmpty else { continue }

            let lastMatch = matches.last!
            let textStartIdx = trimmed.index(trimmed.startIndex, offsetBy: lastMatch.range.location + lastMatch.range.length)
            let lyricText = String(trimmed[textStartIdx...]).trimmingCharacters(in: .whitespaces)
            guard !lyricText.isEmpty else { continue }

            for m in matches {
                var mMin: Double = 0
                var mSec: Double = 0
                var mFrac: Double = 0
                if let r = Range(m.range(at: 1), in: trimmed) { mMin = Double(trimmed[r]) ?? 0 }
                if let r = Range(m.range(at: 2), in: trimmed) { mSec = Double(trimmed[r]) ?? 0 }
                if m.range(at: 3).location != NSNotFound, let r = Range(m.range(at: 3), in: trimmed) {
                    mFrac = Double("0." + trimmed[r]) ?? 0
                }
                let t = (mMin * 60.0) + mSec + mFrac
                rawCues.append((time: t, text: lyricText))
            }
        }

        rawCues.sort { $0.time < $1.time }
        var cues: [SubtitleCue] = []
        for (i, item) in rawCues.enumerated() {
            let nextTime = (i + 1 < rawCues.count) ? rawCues[i + 1].time : (item.time + 6.0)
            let endTime = min(item.time + 10.0, max(item.time + 1.0, nextTime))
            cues.append(SubtitleCue(startTime: item.time, endTime: endTime, text: item.text, position: .bottom))
        }
        return cues
    }

    public static func parseASS(_ raw: String) -> [SubtitleCue] {
        var cues: [SubtitleCue] = []
        let lines = raw.components(separatedBy: .newlines)

        var playResY: Double = 288.0
        var styleAlignments: [String: SubtitlePosition] = [:]
        var styleFormatColumns: [String] = []
        var eventFormatColumns: [String] = []
        var currentSection = ""
        let defaultEventCols = ["layer", "start", "end", "style", "name", "marginl", "marginr", "marginv", "effect", "text"]

        for line in lines {
            let trimmed = line.trimmingCharacters(in: .whitespacesAndNewlines)
            if trimmed.isEmpty || trimmed.hasPrefix(";") { continue }

            if trimmed.hasPrefix("[") && trimmed.hasSuffix("]") {
                currentSection = trimmed.lowercased()
                continue
            }

            if currentSection == "[script info]" {
                if trimmed.lowercased().hasPrefix("playresy:") {
                    let valStr = trimmed.dropFirst("playresy:".count).trimmingCharacters(in: .whitespaces)
                    if let val = Double(valStr), val > 0 {
                        playResY = val
                    }
                }
            } else if currentSection.contains("styles") {
                if trimmed.lowercased().hasPrefix("format:") {
                    let cols = trimmed.dropFirst("format:".count)
                    styleFormatColumns = cols.split(separator: ",").map {
                        $0.trimmingCharacters(in: .whitespaces).lowercased()
                    }
                } else if trimmed.lowercased().hasPrefix("style:") {
                    let body = trimmed.dropFirst("style:".count)
                    let parts = body.split(separator: ",", omittingEmptySubsequences: false).map {
                        $0.trimmingCharacters(in: .whitespaces)
                    }
                    let nameIdx = styleFormatColumns.firstIndex(of: "name") ?? 0
                    let alignIdx = styleFormatColumns.firstIndex(of: "alignment") ?? 18
                    if parts.count > max(nameIdx, alignIdx) {
                        let styleName = parts[nameIdx]
                        if let alignInt = Int(parts[alignIdx]) {
                            if [7, 8, 9].contains(alignInt) {
                                styleAlignments[styleName] = .top
                            } else if [4, 5, 6].contains(alignInt) {
                                styleAlignments[styleName] = .center
                            } else {
                                styleAlignments[styleName] = .bottom
                            }
                        }
                    }
                }
            } else if currentSection == "[events]" || trimmed.lowercased().hasPrefix("dialogue:") {
                if trimmed.lowercased().hasPrefix("format:") {
                    let cols = trimmed.dropFirst("format:".count)
                    eventFormatColumns = cols.split(separator: ",").map {
                        $0.trimmingCharacters(in: .whitespaces).lowercased()
                    }
                } else if trimmed.lowercased().hasPrefix("dialogue:") {
                    let body = String(trimmed.dropFirst("dialogue:".count)).trimmingCharacters(in: .whitespaces)
                    let cols = eventFormatColumns.isEmpty ? defaultEventCols : eventFormatColumns
                    let expectedCols = max(cols.count, 10)
                    let parts = splitASSText(body, maxSplits: expectedCols - 1)
                    let startIdx = cols.firstIndex(of: "start") ?? 1
                    let endIdx = cols.firstIndex(of: "end") ?? 2
                    let styleIdx = cols.firstIndex(of: "style") ?? 3
                    let textIdx = cols.firstIndex(of: "text") ?? (expectedCols - 1)

                    guard parts.count > max(startIdx, endIdx, textIdx) else { continue }
                    guard let start = parseASSTimestamp(parts[startIdx]),
                          let end = parseASSTimestamp(parts[endIdx]) else { continue }

                    let styleName = parts.count > styleIdx ? parts[styleIdx] : "Default"
                    let fallbackPos = styleAlignments[styleName] ?? .bottom
                    let rawText = parts[textIdx]

                    let (detectedPos, cleaned) = cleanSubtitleFormattingAndExtractPosition(
                        rawText,
                        fallbackPosition: fallbackPos,
                        playResY: playResY
                    )
                    if !cleaned.isEmpty {
                        cues.append(SubtitleCue(startTime: start, endTime: end, text: cleaned, position: detectedPos))
                    }
                }
            }
        }

        return cues.sorted { $0.startTime < $1.startTime }
    }

    private static func splitASSText(_ str: String, maxSplits: Int) -> [String] {
        var result: [String] = []
        var currentStart = str.startIndex
        var splits = 0

        for idx in str.indices {
            if str[idx] == "," && splits < maxSplits {
                result.append(String(str[currentStart..<idx]).trimmingCharacters(in: .whitespaces))
                currentStart = str.index(after: idx)
                splits += 1
            }
        }
        result.append(String(str[currentStart...]))
        return result
    }

    private static func parseASSTimestamp(_ str: String) -> Double? {
        // Format: H:MM:SS.cc or HH:MM:SS.cc
        let parts = str.trimmingCharacters(in: .whitespaces).split(separator: ":")
        guard parts.count == 3,
              let h = Double(parts[0]),
              let m = Double(parts[1]),
              let s = Double(parts[2]) else { return nil }
        return (h * 3600.0) + (m * 60.0) + s
    }

    public static func parseWebVTT(_ raw: String) -> [SubtitleCue] {
        if raw.contains("[Events]") || raw.contains("\nDialogue:") {
            return parseASS(raw)
        }

        var cues: [SubtitleCue] = []
        let lines = raw.components(separatedBy: .newlines)

        var currentStart: Double?
        var currentEnd: Double?
        var currentPosition: SubtitlePosition = .bottom
        var currentTextLines: [String] = []

        let timestampRegex = try? NSRegularExpression(
            pattern: #"(?:(\d{1,2}):)?(\d{2}):(\d{2})[.,](\d{1,4})\s*-->\s*(?:(\d{1,2}):)?(\d{2}):(\d{2})[.,](\d{1,4})"#
        )

        func commitCue() {
            if let start = currentStart, let end = currentEnd, !currentTextLines.isEmpty {
                // Deduplicate identical adjacent lines (common in rolling WebVTT / auto-captions)
                var dedupedLines: [String] = []
                for line in currentTextLines {
                    if dedupedLines.last != line {
                        dedupedLines.append(line)
                    }
                }
                let joined = dedupedLines.joined(separator: "\n").trimmingCharacters(in: .whitespacesAndNewlines)
                let (detectedPos, cleaned) = cleanSubtitleFormattingAndExtractPosition(joined, fallbackPosition: currentPosition)
                if !cleaned.isEmpty {
                    cues.append(SubtitleCue(startTime: start, endTime: end, text: cleaned, position: detectedPos))
                }
            }
            currentStart = nil
            currentEnd = nil
            currentPosition = .bottom
            currentTextLines.removeAll()
        }

        for line in lines {
            let trimmed = line.trimmingCharacters(in: .whitespacesAndNewlines)

            // Skip WebVTT header or metadata lines, and commit cue when encountering blank line after text
            if trimmed.isEmpty {
                if !currentTextLines.isEmpty {
                    commitCue()
                }
                continue
            }
            if trimmed.hasPrefix("WEBVTT") || trimmed.hasPrefix("Kind:") || trimmed.hasPrefix("Language:") || trimmed.hasPrefix("NOTE") {
                continue
            }

            // Check for timestamp line
            if let regex = timestampRegex,
               let match = regex.firstMatch(in: trimmed, range: NSRange(location: 0, length: trimmed.utf16.count)) {
                commitCue()

                let start = parseTimestampMatch(trimmed, match: match, isEnd: false)
                let end = parseTimestampMatch(trimmed, match: match, isEnd: true)
                currentStart = start
                currentEnd = end

                // Detect WebVTT cue settings on the timestamp line
                if trimmed.contains("line:0%") || trimmed.contains("line:10%") || trimmed.contains("line:15%") || trimmed.contains("line:20%") {
                    currentPosition = .top
                } else if trimmed.contains("line:40%") || trimmed.contains("line:50%") || trimmed.contains("line:60%") {
                    currentPosition = .center
                } else {
                    currentPosition = .bottom
                }
                continue
            }

            // Skip numeric cue indices in SRT format when not inside an active cue
            if currentStart == nil, Int(trimmed) != nil {
                continue
            }

            // If we have an active timestamp, this is text content
            if currentStart != nil {
                currentTextLines.append(trimmed)
            }
        }

        commitCue()
        return cues.sorted { $0.startTime < $1.startTime }
    }

    private static func parseTimestampMatch(_ str: String, match: NSTextCheckingResult, isEnd: Bool) -> Double {
        let base = isEnd ? 5 : 1
        let hRange = match.range(at: base)
        let mRange = match.range(at: base + 1)
        let sRange = match.range(at: base + 2)
        let msRange = match.range(at: base + 3)

        var hours: Double = 0
        if hRange.location != NSNotFound, let r = Range(hRange, in: str) {
            hours = Double(str[r]) ?? 0
        }
        var minutes: Double = 0
        if mRange.location != NSNotFound, let r = Range(mRange, in: str) {
            minutes = Double(str[r]) ?? 0
        }
        var seconds: Double = 0
        if sRange.location != NSNotFound, let r = Range(sRange, in: str) {
            seconds = Double(str[r]) ?? 0
        }
        var msFraction: Double = 0
        if msRange.location != NSNotFound, let r = Range(msRange, in: str) {
            msFraction = Double("0." + str[r]) ?? 0
        }

        return (hours * 3600.0) + (minutes * 60.0) + seconds + msFraction
    }

    /// Strips non-position ASS styles (font, size, color, borders, effects) and HTML entities,
    /// while preserving semantic positioning (top, bottom, center).
    public static func cleanSubtitleFormattingAndExtractPosition(
        _ text: String,
        fallbackPosition: SubtitlePosition,
        playResY: Double = 1080.0
    ) -> (SubtitlePosition, String) {
        var position = fallbackPosition
        var result = text

        // 1. Check ASS position tags before stripping styles:
        // \an7, \an8, \an9 (or legacy \a5, \a6, \a7) = Top
        if result.contains("\\an7") || result.contains("\\an8") || result.contains("\\an9") ||
           result.contains("\\a5") || result.contains("\\a6") || result.contains("\\a7") {
            position = .top
        } else if result.contains("\\an4") || result.contains("\\an5") || result.contains("\\an6") ||
                  result.contains("\\a9") || result.contains("\\a10") || result.contains("\\a11") {
            position = .center
        } else if result.contains("\\an1") || result.contains("\\an2") || result.contains("\\an3") ||
                  result.contains("\\a1") || result.contains("\\a2") || result.contains("\\a3") {
            position = .bottom
        }

        // Check explicit \pos(x, y) if present (supports integer and decimal coordinates)
        if let posRegex = try? NSRegularExpression(pattern: #"\\pos\(\s*[\d.]+\s*,\s*([\d.]+)\s*\)"#) {
            if let match = posRegex.firstMatch(in: result, range: NSRange(location: 0, length: result.utf16.count)),
               match.numberOfRanges > 1,
               let r = Range(match.range(at: 1), in: result),
               let y = Double(result[r]) {
                let effectiveResY = playResY > 0 ? playResY : 1080.0
                let normalizedY = y > effectiveResY ? (y / 1080.0) : (y / effectiveResY)
                if normalizedY < 0.30 {
                    position = .top
                } else if normalizedY > 0.65 {
                    position = .bottom
                } else {
                    position = .center
                }
            }
        }

        // Ignore ASS vector drawing commands (\p1 ... \p0)
        if result.contains("\\p1") || result.contains("\\p2") || result.contains("\\p4") {
            return (position, "")
        }

        // 2. Strip all ASS style override tags ({...}): font, size, color, alpha, karaoke, bold, italic, borders, etc.
        if let assRegex = try? NSRegularExpression(pattern: #"\{[^}]+\}"#) {
            result = assRegex.stringByReplacingMatches(
                in: result,
                options: [],
                range: NSRange(location: 0, length: result.utf16.count),
                withTemplate: ""
            )
        }
        result = result.replacingOccurrences(of: "\\N", with: "\n")
        result = result.replacingOccurrences(of: "\\n", with: "\n")
        result = result.replacingOccurrences(of: "\\h", with: " ")

        // 3. Strip XML/HTML tags
        if let tagRegex = try? NSRegularExpression(pattern: #"<[^>]+>"#) {
            result = tagRegex.stringByReplacingMatches(
                in: result,
                options: [],
                range: NSRange(location: 0, length: result.utf16.count),
                withTemplate: ""
            )
        }

        // 4. Decode common HTML entities
        result = result
            .replacingOccurrences(of: "&amp;", with: "&")
            .replacingOccurrences(of: "&lt;", with: "<")
            .replacingOccurrences(of: "&gt;", with: ">")
            .replacingOccurrences(of: "&quot;", with: "\"")
            .replacingOccurrences(of: "&#39;", with: "'")
            .replacingOccurrences(of: "&nbsp;", with: " ")

        return (position, result.trimmingCharacters(in: .whitespacesAndNewlines))
    }
}
