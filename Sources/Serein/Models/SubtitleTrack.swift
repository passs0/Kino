import Foundation

/// Individual subtitle cue containing start time, end time, and plain text.
public struct SubtitleCue: Identifiable, Sendable {
    public let id = UUID()
    public let startTime: Double
    public let endTime: Double
    public let text: String

    public init(startTime: Double, endTime: Double, text: String) {
        self.startTime = startTime
        self.endTime = endTime
        self.text = text
    }
}

/// Represents an available subtitle track (embedded local stream or online WebVTT).
public struct SubtitleTrack: Identifiable, Hashable, Sendable {
    public let id: String
    public let name: String
    public let languageCode: String?
    public let isAutoGenerated: Bool
    public var vttURL: URL?
    public let streamIndex: Int?
    public let sourceURL: URL?
    public let isDefault: Bool

    public init(
        id: String,
        name: String,
        languageCode: String? = nil,
        isAutoGenerated: Bool = false,
        vttURL: URL? = nil,
        streamIndex: Int? = nil,
        sourceURL: URL? = nil,
        isDefault: Bool = false
    ) {
        self.id = id
        self.name = name
        self.languageCode = languageCode
        self.isAutoGenerated = isAutoGenerated
        self.vttURL = vttURL
        self.streamIndex = streamIndex
        self.sourceURL = sourceURL
        self.isDefault = isDefault
    }
}

/// Fast WebVTT and SRT parser converting raw subtitle text into timestamped cues.
public enum SubtitleParser {
    public static func parseWebVTT(_ raw: String) -> [SubtitleCue] {
        var cues: [SubtitleCue] = []
        let lines = raw.components(separatedBy: .newlines)

        var currentStart: Double?
        var currentEnd: Double?
        var currentTextLines: [String] = []

        let timestampRegex = try? NSRegularExpression(
            pattern: #"(?:(\d{1,2}):)?(\d{2}):(\d{2})[.,](\d{3})\s*-->\s*(?:(\d{1,2}):)?(\d{2}):(\d{2})[.,](\d{3})"#
        )

        func commitCue() {
            if let start = currentStart, let end = currentEnd, !currentTextLines.isEmpty {
                let joined = currentTextLines.joined(separator: "\n").trimmingCharacters(in: .whitespacesAndNewlines)
                let cleaned = cleanSubtitleFormatting(joined)
                if !cleaned.isEmpty {
                    cues.append(SubtitleCue(startTime: start, endTime: end, text: cleaned))
                }
            }
            currentStart = nil
            currentEnd = nil
            currentTextLines.removeAll()
        }

        for line in lines {
            let trimmed = line.trimmingCharacters(in: .whitespacesAndNewlines)

            // Skip WebVTT header or metadata lines
            if trimmed.isEmpty {
                commitCue()
                continue
            }
            if trimmed.hasPrefix("WEBVTT") || trimmed.hasPrefix("Kind:") || trimmed.hasPrefix("Language:") || trimmed.hasPrefix("NOTE") {
                continue
            }

            // Check for timestamp line
            if let regex = timestampRegex,
               let match = regex.firstMatch(in: trimmed, range: NSRange(location: 0, length: trimmed.utf16.count)) {
                commitCue()

                let start = parseTimestampMatch(trimmed, match: match, isEnd: false)
                let end = parseTimestampMatch(trimmed, match: match, isEnd: true)
                currentStart = start
                currentEnd = end
                continue
            }

            // If we have an active timestamp, this is text content
            if currentStart != nil {
                currentTextLines.append(trimmed)
            }
        }

        commitCue()
        return cues.sorted { $0.startTime < $1.startTime }
    }

    private static func parseTimestampMatch(_ str: String, match: NSTextCheckingResult, isEnd: Bool) -> Double {
        let base = isEnd ? 5 : 1
        let hRange = match.range(at: base)
        let mRange = match.range(at: base + 1)
        let sRange = match.range(at: base + 2)
        let msRange = match.range(at: base + 3)

        var hours: Double = 0
        if hRange.location != NSNotFound, let r = Range(hRange, in: str) {
            hours = Double(str[r]) ?? 0
        }
        var minutes: Double = 0
        if mRange.location != NSNotFound, let r = Range(mRange, in: str) {
            minutes = Double(str[r]) ?? 0
        }
        var seconds: Double = 0
        if sRange.location != NSNotFound, let r = Range(sRange, in: str) {
            seconds = Double(str[r]) ?? 0
        }
        var ms: Double = 0
        if msRange.location != NSNotFound, let r = Range(msRange, in: str) {
            ms = Double(str[r]) ?? 0
        }

        return (hours * 3600.0) + (minutes * 60.0) + seconds + (ms / 1000.0)
    }

    /// Strips inline WebVTT/ASS formatting tags (<c>, <v>, <b>, <i>, {\an8}, etc.) and HTML entities.
    private static func cleanSubtitleFormatting(_ text: String) -> String {
        var result = text
        // Strip ASS/SSA style override tags like {\an8}, {\b1}, etc.
        if let assRegex = try? NSRegularExpression(pattern: #"\{[^}]+\}"#) {
            result = assRegex.stringByReplacingMatches(
                in: result,
                options: [],
                range: NSRange(location: 0, length: result.utf16.count),
                withTemplate: ""
            )
        }
        result = result.replacingOccurrences(of: "\\N", with: "\n")

        // Strip XML/HTML tags
        if let tagRegex = try? NSRegularExpression(pattern: #"<[^>]+>"#) {
            result = tagRegex.stringByReplacingMatches(
                in: result,
                options: [],
                range: NSRange(location: 0, length: result.utf16.count),
                withTemplate: ""
            )
        }
        // Decode common entities
        result = result
            .replacingOccurrences(of: "&amp;", with: "&")
            .replacingOccurrences(of: "&lt;", with: "<")
            .replacingOccurrences(of: "&gt;", with: ">")
            .replacingOccurrences(of: "&quot;", with: "\"")
            .replacingOccurrences(of: "&#39;", with: "'")
            .replacingOccurrences(of: "&nbsp;", with: " ")

        return result.trimmingCharacters(in: .whitespacesAndNewlines)
    }
}
